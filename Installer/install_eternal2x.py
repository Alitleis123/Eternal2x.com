from __future__ import annotations

import os
from pathlib import Path
import shutil
import sys

DEFAULT_UPDATE_URL = (
    "https://raw.githubusercontent.com/"
    "Alitleis123/Eternal2x.com/main/update/latest.json"
)


def _resolve_scripts_root() -> Path:
    """Resolve's per-user Fusion/Scripts folder, as Blackmagic documents it."""
    if sys.platform.startswith("win"):
        appdata = os.environ.get("APPDATA")
        if not appdata:
            raise RuntimeError("APPDATA is not set.")
        # Windows keeps it under Support. Without that folder Resolve never
        # scans the script, so the panel would not show up at all.
        return (Path(appdata) / "Blackmagic Design" / "DaVinci Resolve"
                / "Support" / "Fusion" / "Scripts")
    if sys.platform == "darwin":
        return (Path.home() / "Library" / "Application Support"
                / "Blackmagic Design" / "DaVinci Resolve" / "Fusion" / "Scripts")
    return Path.home() / ".local" / "share" / "DaVinciResolve" / "Fusion" / "Scripts"


def _resolve_scripts_dir() -> Path:
    """Where the launcher goes.

    Utility scripts are listed under Workspace > Scripts on every page. Comp
    scripts are only listed on the Fusion page, which is not where anyone
    works with a timeline clip.
    """
    return _resolve_scripts_root() / "Utility"


# The first line of the Python launcher an older installer generated in
# Utility. Resolve lists it as a second "Eternal2x" that runs the old plugin.
OLD_PY_LAUNCHER_MARK = "GENERATED by Installer/install_eternal2x.py"


def remove_old_install() -> None:
    """Remove launchers earlier versions left behind, so it is not listed twice."""
    try:
        root = _resolve_scripts_root()
    except RuntimeError:
        return
    # Only the old launcher goes here. The conf beside it holds the panel's
    # settings, so write_config reads it and removes it once they are saved.
    try:
        (root / "Comp" / "Eternal2x.lua").unlink()
    except OSError:
        pass
    old_py = root / "Utility" / "Eternal2x.py"
    try:
        if OLD_PY_LAUNCHER_MARK in old_py.read_text(encoding="utf-8",
                                                     errors="replace"):
            old_py.unlink()
    except OSError:
        pass


def _pick_python(repo_root: Path) -> str:
    # Past a venv, the Python running this is the one the user chose and
    # installed the requirements into. `python` on PATH can be another one,
    # or on Windows the Microsoft Store stub, which runs nothing.
    if sys.platform.startswith("win"):
        venv_python = repo_root / ".venv" / "Scripts" / "python.exe"
        if venv_python.exists():
            return str(venv_python)
        return sys.executable or shutil.which("python") or "python"
    venv_python = repo_root / ".venv" / "bin" / "python"
    if venv_python.exists():
        return str(venv_python)
    return sys.executable or shutil.which("python3") or shutil.which("python") or "python3"


# Panel defaults. The UI rewrites this file whenever a setting changes.
PANEL_DEFAULTS = {
    "output_dir": "",
    "upscale": "true",
    "interpolate": "true",
    "grain": "false",
    "base_hold": "0",
    "format": "png",
}


# Where this copy of the plugin lives and updates from. Every install writes
# these afresh. Everything else in the file is the user's.
INSTALL_KEYS = ("repo_root", "python", "update_url")


def write_config(dest_dir: Path, repo_root: Path, python_path: str,
                 update_url: str = DEFAULT_UPDATE_URL) -> Path:
    """Write Eternal2x.conf beside the launcher.

    Both installers call this so the file they produce cannot drift apart.
    Plain UTF-8 with no BOM: the panel and the updater both read it. The
    panel saves its settings here, so a reinstall keeps them, and any key a
    later version added, rather than turning updates back on.

    Versions up to 0.3.1 kept the conf beside a launcher in Comp. With none
    here yet, its settings are read from there, and it is removed only after
    this one is written. Moving it first could fail halfway, and the next
    install would then find defaults here and delete the only real copy.
    """
    conf_path = dest_dir / "Eternal2x.conf"
    legacy = dest_dir.parent / "Comp" / "Eternal2x.conf"
    if legacy == conf_path:
        legacy = None   # installing into Comp itself: there is no older copy
    settings = {"auto_update": "true", **PANEL_DEFAULTS}
    # Only a conf that is not there means defaults. One that cannot be read
    # stops the install, rather than being replaced by defaults unread.
    try:
        saved = (conf_path if conf_path.exists() or not legacy else legacy).read_text(
            encoding="utf-8-sig", errors="replace")
    except FileNotFoundError:
        saved = ""
    for line in saved.splitlines():
        key, sep, value = line.partition("=")
        if sep and key.strip() and key.strip() not in INSTALL_KEYS:
            settings[key.strip()] = value.strip()
    lines = [
        f"repo_root={repo_root}",
        f"python={python_path}",
        f"update_url={update_url}",
    ]
    lines += [f"{k}={v}" for k, v in settings.items()]
    # Written beside it and renamed into place, so a write cut off partway
    # leaves the old conf, or none, never a partial one the next install trusts.
    staged = conf_path.with_name(conf_path.name + ".new")
    try:
        staged.write_text("\n".join(lines) + "\n", encoding="utf-8")
        os.replace(staged, conf_path)
    except OSError:
        try:
            staged.unlink()
        except OSError:
            pass
        raise
    if legacy:
        try:
            legacy.unlink()
        except OSError:
            pass
    return conf_path


def main() -> int:
    repo_root = Path(__file__).resolve().parent.parent
    src_lua = repo_root / "Installer" / "Eternal2xLauncher.lua"

    if not src_lua.exists():
        print(f"Missing launcher script: {src_lua}")
        return 1

    dest_dir = _resolve_scripts_dir()
    dest_dir.mkdir(parents=True, exist_ok=True)
    remove_old_install()

    dest_lua = dest_dir / "Eternal2x.lua"
    shutil.copy2(src_lua, dest_lua)

    conf_path = write_config(dest_dir, repo_root, _pick_python(repo_root))

    print("Installed Eternal2x launcher.")
    print(f"Launcher: {dest_lua}")
    print(f"Config: {conf_path}")
    print("Restart Resolve to see Workspace > Scripts > Eternal2x.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
